"""Vendors the Phosphor icons MUSE uses and generates both apps' icon code from design/icons/icons.txt.

    PHOSPHOR=/path/to/unpacked/@phosphor-icons/core python3 design/icons/build.py   # vendor + generate
    python3 design/icons/build.py                                                   # regenerate from the vendored SVGs

Writes:
  design/icons/phosphor/<name>.svg                         the Regular SVGs we use (pinned @phosphor-icons/core 2.1.1)
  android/.../ui/theme/PhosphorIcons.kt                    path data + the old-name aliases, drawn as ImageVectors
  mac/Muse/Resources/Phosphor.xcassets/ph.<name>.imageset  template vector images
  mac/Muse/Theme/PhosphorMap.swift                         SF Symbol name -> Phosphor name
plans/design-direction.md §5 has the why. Every Phosphor icon is one filled <path> in a 256 x 256 box.
"""
import json, os, re, shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
VENDOR = HERE / "phosphor"
KT = REPO / "android/app/src/main/kotlin/studio/muse/app/ui/theme/PhosphorIcons.kt"
XC = REPO / "mac/Muse/Resources/Phosphor.xcassets"
SWIFT = REPO / "mac/Muse/Theme/PhosphorMap.swift"

def read_list():
    sections, cur = {"android": {}, "mac": {}, "extra": {}}, None
    for raw in (HERE / "icons.txt").read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line: continue
        if line.startswith("["): cur = line.strip("[]"); continue
        parts = line.split()
        sections[cur][parts[0]] = parts[-1]
    return sections

def main():
    s = read_list()
    names = sorted(set(s["android"].values()) | set(s["mac"].values()) | set(s["extra"].values()))
    src = os.environ.get("PHOSPHOR")
    if src:
        reg = Path(src) / "assets/regular"
        VENDOR.mkdir(exist_ok=True)
        for old in VENDOR.glob("*.svg"): old.unlink()
        for n in names: shutil.copy(reg / f"{n}.svg", VENDOR / f"{n}.svg")
        shutil.copy(Path(src) / "LICENSE", HERE / "LICENSE")
    paths = {}
    for n in names:
        svg = (VENDOR / f"{n}.svg").read_text()
        d = re.findall(r'<path d="([^"]+)"', svg)
        assert len(d) == 1 and "<path" in svg and svg.count("<") == 3, f"{n}: expected one <path>"
        paths[n] = d[0]

    # Android: path data, drawn as filled ImageVectors in the 256 viewport.
    kt = ["// Generated by design/icons/build.py from design/icons/icons.txt. Do not edit by hand.",
          "// Phosphor Icons, Regular, @phosphor-icons/core 2.1.1. MIT License, Copyright (c) 2023 Phosphor Icons (design/icons/LICENSE).",
          "package studio.muse.app.ui.theme", "",
          "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.graphics.SolidColor",
          "import androidx.compose.ui.graphics.vector.ImageVector", "import androidx.compose.ui.graphics.vector.addPathNodes",
          "import androidx.compose.ui.unit.dp", "",
          "/** MUSE's one icon set (plans/design-direction.md §5). [get] takes a Phosphor name or an old MUSE icon name. */",
          "object PhosphorIcons {",
          "    /** Old MUSE icon names (Ic, EIc, SIc, CamIc) -> Phosphor names. */",
          "    val ALIASES: Map<String, String> = mapOf(",
          *[f'        "{k}" to "{v}",' for k, v in s["android"].items()],
          "    )", "",
          "    private val PATHS: Map<String, String> = mapOf(",
          *[f'        "{n}" to "{paths[n]}",' for n in names],
          "    )", "",
          "    private val cache = HashMap<String, ImageVector>()", "",
          "    /** The Phosphor name an icon name resolves to, or null when it has none. */",
          "    fun resolve(name: String): String? = (ALIASES[name] ?: name).takeIf { it in PATHS }", "",
          "    fun get(name: String): ImageVector = cache.getOrPut(name) {",
          '        val ph = resolve(name) ?: error("Unknown icon $name (add it to design/icons/icons.txt)")',
          "        ImageVector.Builder(ph, 24.dp, 24.dp, 256f, 256f).apply {",
          "            addPath(pathData = addPathNodes(PATHS.getValue(ph)), fill = SolidColor(Color.Black))",
          "        }.build()", "    }", "}", ""]
    KT.write_text("\n".join(kt))

    # Mac: one template vector imageset per icon, plus the SF Symbol map.
    if XC.exists(): shutil.rmtree(XC)
    XC.mkdir(parents=True)
    (XC / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    for n in names:
        d = XC / f"ph.{n}.imageset"; d.mkdir()
        (d / f"{n}.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256"><path fill="#000000" d="{paths[n]}"/></svg>\n')
        (d / "Contents.json").write_text(json.dumps({"images": [{"filename": f"{n}.svg", "idiom": "universal"}], "info": {"author": "xcode", "version": 1},
                                                     "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"}}, indent=2) + "\n")
    sw = ["// Generated by design/icons/build.py from design/icons/icons.txt. Do not edit by hand.",
          "// Phosphor Icons, Regular, @phosphor-icons/core 2.1.1. MIT License, Copyright (c) 2023 Phosphor Icons (design/icons/LICENSE).", "",
          "enum PhosphorMap {",
          "    /// SF Symbol names still written in the code -> the Phosphor icon drawn instead.",
          "    static let sf: [String: String] = [",
          *[f'        "{k}": "{v}",' for k, v in s["mac"].items()],
          "    ]", "",
          "    /// Every vendored Phosphor name (asset `ph.<name>` in Phosphor.xcassets).",
          "    static let names: Set<String> = [",
          *[f'        "{n}",' for n in names],
          "    ]", "}", ""]
    SWIFT.write_text("\n".join(sw))
    print(f"{len(names)} icons; {len(s['android'])} Android aliases; {len(s['mac'])} SF names")

if __name__ == "__main__":
    main()
