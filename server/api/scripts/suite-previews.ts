// AI suite (workstream 1): writes src/suite/previews.data.ts from design/previews/manifest.tsv (the composer's move loops,
// lighting and angle stills, rendered in Blender). The apps bundle design/previews as `previews/`; the catalogue names
// each option's files relative to it. Run: npx tsx scripts/suite-previews.ts (a server test fails if the file is stale).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const MANIFEST = path.resolve(here, '../../../design/previews/manifest.tsv');
export const OUT = path.resolve(here, '../src/suite/previews.data.ts');

export function previewsModule(tsv = fs.readFileSync(MANIFEST, 'utf8')): string {
  const rows = tsv.trim().split('\n').slice(1).map(l => l.split('\t')).filter(c => c[0]);
  const map: Record<string, { video?: string; poster: string; seconds?: number }> = {};
  for (const [id, file, poster, seconds] of rows) {
    const isVideo = /\.(mp4|webm|mov)$/i.test(file!);
    map[id!] = isVideo ? { video: file!, poster: poster || file!.replace(/\.\w+$/, '.jpg'), seconds: Number(seconds) || undefined } : { poster: file! };
  }
  const keys = Object.keys(map).sort();
  const body = keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`).join('\n');
  return `// Generated by scripts/suite-previews.ts from design/previews/manifest.tsv. Do not edit by hand.\n` +
    `/** Composer previews by "<group>/<id>" (moves, lighting, angles); paths are relative to the apps' bundled \`previews/\` folder. */\n` +
    `export const PREVIEWS: Record<string, { video?: string; poster: string; seconds?: number }> = {\n${body}\n};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(OUT, previewsModule());
  console.log(`wrote ${OUT}`);
}
